"""Carry out a RepoPlan. Only called when not in dry-run mode."""

from __future__ import annotations

import urllib.parse

from .client import ApiError, Client
from .config import FactoryConfig
from .plan import Change, RepoPlan


def _q(s: str) -> str:
    return urllib.parse.quote(s, safe="")


def pr_body(plan: RepoPlan, cfg: FactoryConfig) -> str:
    lines = [
        f"This PR was opened by [{cfg.workflows_repo}](https://github.com/{cfg.workflows_repo}) "
        "to bring this repo in line with the factory baseline.",
        "",
        "### Files",
        "",
    ]
    lines += [f"- `{c.target}`: {c.action}" for c in plan.changes if c.item != "files" and c.target in plan.files]
    drift = [c for c in plan.changes if c.action == "drift"]
    if drift:
        lines += ["", "### Left alone (drift)", ""] + [f"- `{c.target}`: {c.detail}" for c in drift]
    lines += [
        "",
        f"Files marked `{cfg.marker}` are kept in sync. Remove the marker from a file to take ownership, "
        "or skip items in `.github/factory.yml`.",
        "",
        "- [x] CHANGELOG.md updated (or the `skip-changelog` label applied)",
    ]
    return "\n".join(lines)


def _sync_files(client: Client, plan: RepoPlan, cfg: FactoryConfig) -> str:
    """Point the sync branch at one commit on top of the default branch. Returns 'created', 'updated' or 'unchanged'."""
    fn = plan.full_name
    base_sha = client.get(f"/repos/{fn}/git/ref/heads/{plan.default_branch}")["object"]["sha"]
    base_tree = client.get(f"/repos/{fn}/git/commits/{base_sha}")["tree"]["sha"]
    tree = client.post(
        f"/repos/{fn}/git/trees",
        {
            "base_tree": base_tree,
            "tree": [{"path": p, "mode": "100644", "type": "blob", "content": c} for p, c in sorted(plan.files.items())],
        },
    )["sha"]
    try:
        head = client.get(f"/repos/{fn}/git/ref/heads/{cfg.sync_branch}")["object"]["sha"]
    except ApiError as e:
        if e.status != 404:
            raise
        head = None
    if head:
        commit = client.get(f"/repos/{fn}/git/commits/{head}")
        if commit["tree"]["sha"] == tree and [p["sha"] for p in commit.get("parents", [])] == [base_sha]:
            return "unchanged"
    new = client.post(
        f"/repos/{fn}/git/commits",
        {
            "message": f"chore: sync factory baseline\n\nGenerated by {cfg.workflows_repo}.",
            "tree": tree,
            "parents": [base_sha],
        },
    )["sha"]
    if head:
        client.patch(f"/repos/{fn}/git/refs/heads/{cfg.sync_branch}", {"sha": new, "force": True})
        return "updated"
    client.post(f"/repos/{fn}/git/refs", {"ref": f"refs/heads/{cfg.sync_branch}", "sha": new})
    return "created"


def _apply_change(client: Client, plan: RepoPlan, cfg: FactoryConfig, c: Change) -> None:
    fn = plan.full_name
    if c.item == "settings":
        client.patch(f"/repos/{fn}", c.payload)
    elif c.item == "secret-scanning":
        client.patch(f"/repos/{fn}", c.payload)
    elif c.item == "vulnerability-alerts":
        client.put(f"/repos/{fn}/vulnerability-alerts")
    elif c.item == "ruleset" and c.action == "create":
        client.post(f"/repos/{fn}/rulesets", c.payload["body"])
    elif c.item == "ruleset" and c.action == "update":
        client.put(f"/repos/{fn}/rulesets/{c.payload['id']}", c.payload["body"])
    elif c.item == "labels" and c.action == "create":
        client.post(f"/repos/{fn}/labels", c.payload["body"])
    elif c.item == "labels" and c.action == "update":
        client.patch(f"/repos/{fn}/labels/{_q(c.payload['current'])}", c.payload["body"])
    elif c.item == "files" and c.action in ("open-pr", "update-pr"):
        state = _sync_files(client, plan, cfg)
        body = pr_body(plan, cfg)
        if plan.open_pr:
            client.patch(f"/repos/{fn}/pulls/{plan.open_pr['number']}", {"body": body})
            c.detail += f" (branch {state})"
            return
        pr = client.post(
            f"/repos/{fn}/pulls",
            {
                "title": "chore: sync factory baseline",
                "head": cfg.sync_branch,
                "base": plan.default_branch,
                "body": body,
            },
        )
        try:
            client.post(f"/repos/{fn}/issues/{pr['number']}/labels", {"labels": ["factory", "skip-changelog"]})
        except ApiError:
            pass  # labels may be skipped for this repo
        c.detail += f" → {pr.get('html_url', '#' + str(pr['number']))}"
    # File create/update changes are delivered by the PR step above.


def apply_plan(client: Client, plan: RepoPlan, cfg: FactoryConfig) -> None:
    for c in list(plan.changes):
        if not c.writes or (c.item not in ("settings", "secret-scanning", "vulnerability-alerts", "ruleset", "labels", "files")):
            continue
        try:
            _apply_change(client, plan, cfg, c)
            c.detail = (c.detail + " ✓").strip()
        except ApiError as e:
            if c.item == "secret-scanning" and e.status in (403, 422):
                c.action, c.detail = "unavailable", f"GitHub refused ({e.message})"
            else:
                plan.add(c.item, "error", c.target, f"apply failed: {e}")
